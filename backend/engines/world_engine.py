"""
World Engine (backend/engines/world_engine.py)
Builds complete 3D Roblox scenes, Lighting & Atmosphere configurations,
spawn zones, and multi-asset spatial layouts in Workspace.
"""

from typing import Any, Dict, List


BIOME_PRESETS: Dict[str, Dict[str, Any]] = {
    "CyberpunkOrbital": {
        "ambient": [18, 24, 38],
        "outdoor_ambient": [30, 41, 59],
        "clock_time": 21.5,
        "brightness": 2.4,
        "atmosphere_density": 0.34,
        "atmosphere_color": [14, 165, 233],
    },
    "MedievalForge": {
        "ambient": [42, 28, 22],
        "outdoor_ambient": [68, 45, 34],
        "clock_time": 18.2,
        "brightness": 2.1,
        "atmosphere_density": 0.42,
        "atmosphere_color": [249, 115, 22],
    },
    "ArcticResearchBase": {
        "ambient": [38, 52, 68],
        "outdoor_ambient": [96, 125, 155],
        "clock_time": 11.0,
        "brightness": 2.8,
        "atmosphere_density": 0.28,
        "atmosphere_color": [186, 230, 253],
    },
}


class WorldEngine:
    def generate_world_lighting_luau(
        self,
        scene_name: str,
        biome_key: str,
        placed_assets: List[Dict[str, Any]],
    ) -> str:
        biome = BIOME_PRESETS.get(biome_key, BIOME_PRESETS["CyberpunkOrbital"])
        ar, ag, ab = biome["ambient"]
        oar, oag, oab = biome["outdoor_ambient"]
        at_r, at_g, at_b = biome["atmosphere_color"]

        lines = [
            "--!strict",
            f"-- Generated by Forge AI World Engine: {scene_name} ({biome_key})",
            "local Lighting = game:GetService(\"Lighting\")",
            "local Workspace = game:GetService(\"Workspace\")",
            "",
            f"local {scene_name}World = {{}}",
            "",
            f"function {scene_name}World.ConfigureEnvironment(): Folder",
            f"    Lighting.Ambient = Color3.fromRGB({ar}, {ag}, {ab})",
            f"    Lighting.OutdoorAmbient = Color3.fromRGB({oar}, {oag}, {oab})",
            f"    Lighting.ClockTime = {biome['clock_time']}",
            f"    Lighting.Brightness = {biome['brightness']}",
            "    Lighting.GlobalShadows = true",
            "",
            "    local atmosphere = Lighting:FindFirstChildOfClass(\"Atmosphere\") or Instance.new(\"Atmosphere\")",
            f"    atmosphere.Density = {biome['atmosphere_density']}",
            f"    atmosphere.Color = Color3.fromRGB({at_r}, {at_g}, {at_b})",
            "    atmosphere.Parent = Lighting",
            "",
            "    local worldFolder = Instance.new(\"Folder\")",
            f"    worldFolder.Name = \"{scene_name}_Zone\"",
            "    worldFolder.Parent = Workspace",
        ]

        for idx, item in enumerate(placed_assets):
            name = item.get("name", f"ZoneProp_{idx + 1}")
            pos = item.get("position", [idx * 14.0, 0.0, 0.0])
            px, py, pz = (pos + [0.0, 0.0, 0.0])[:3]
            lines.extend([
                f"    local marker_{idx + 1} = Instance.new(\"Part\")",
                f"    marker_{idx + 1}.Name = \"{name}_Anchor\"",
                "    marker_{0}.Size = Vector3.new(6, 0.5, 6)".format(idx + 1),
                f"    marker_{idx + 1}.Position = Vector3.new({px:.1f}, {py:.1f}, {pz:.1f})",
                f"    marker_{idx + 1}.Anchored = true",
                f"    marker_{idx + 1}.Material = Enum.Material.Neon",
                f"    marker_{idx + 1}.Parent = worldFolder",
            ])

        lines.extend([
            "    return worldFolder",
            "end",
            "",
            f"return {scene_name}World",
        ])
        return "\n".join(lines)
