/**
 * @module worldEngine
 * @description
 * Engine 5/7 — World, Biome Lighting & Spatial Scene Assembly Engine (TypeScript Server Module).
 *
 * RESPONSIBILITIES:
 * 1. Provide deterministic `Lighting` and `Atmosphere` configurations for each biome preset
 *    (`CyberpunkOrbital`, `MedievalForge`, `ArcticResearchBase`).
 * 2. Generate `--!strict` Luau scene modules (`generateWorldEnvironmentLuau`) that configure
 *    environmental lighting and spawn anchored `MeshPart` spatial pads in `Workspace`.
 */

export type BiomePreset = 'CyberpunkOrbital' | 'MedievalForge' | 'ArcticResearchBase';

export interface BiomeLightingConfig {
  ambient: [number, number, number];
  outdoor: [number, number, number];
  clockTime: number;
  brightness: number;
  density: number;
  atmoColor: [number, number, number];
}

export const BIOME_LIGHTING_CONFIGS: Record<BiomePreset, BiomeLightingConfig> = {
  CyberpunkOrbital: {
    ambient: [18, 24, 38],
    outdoor: [30, 41, 59],
    clockTime: 21.5,
    brightness: 2.4,
    density: 0.34,
    atmoColor: [14, 165, 233],
  },
  MedievalForge: {
    ambient: [42, 28, 22],
    outdoor: [68, 45, 34],
    clockTime: 18.2,
    brightness: 2.1,
    density: 0.42,
    atmoColor: [249, 115, 22],
  },
  ArcticResearchBase: {
    ambient: [38, 52, 68],
    outdoor: [96, 125, 155],
    clockTime: 11.0,
    brightness: 2.8,
    density: 0.28,
    atmoColor: [186, 230, 253],
  },
};

export function generateWorldEnvironmentLuau(
  sceneName: string,
  biome: BiomePreset,
  placedAssetNames: string[]
): string {
  const safeScene = sceneName.replace(/[^a-zA-Z0-9_]/g, '') || 'ForgeWorldScene';
  const biomeConfig = BIOME_LIGHTING_CONFIGS[biome] || BIOME_LIGHTING_CONFIGS.CyberpunkOrbital;

  const lines: string[] = [
    '--!strict',
    `-- Generated by Forge AI World Engine: ${safeScene} (Biome: ${biome})`,
    'local Lighting = game:GetService("Lighting")',
    'local ReplicatedStorage = game:GetService("ReplicatedStorage")',
    'local Workspace = game:GetService("Workspace")',
    '',
    `local ${safeScene}World = {}`,
    '',
    `function ${safeScene}World.BuildEnvironment(): Folder`,
    `    Lighting.Ambient = Color3.fromRGB(${biomeConfig.ambient.join(', ')})`,
    `    Lighting.OutdoorAmbient = Color3.fromRGB(${biomeConfig.outdoor.join(', ')})`,
    `    Lighting.ClockTime = ${biomeConfig.clockTime}`,
    `    Lighting.Brightness = ${biomeConfig.brightness}`,
    '    Lighting.GlobalShadows = true',
    '',
    '    local atmosphere = Lighting:FindFirstChildOfClass("Atmosphere") or Instance.new("Atmosphere")',
    `    atmosphere.Density = ${biomeConfig.density}`,
    `    atmosphere.Color = Color3.fromRGB(${biomeConfig.atmoColor.join(', ')})`,
    '    atmosphere.Parent = Lighting',
    '',
    '    local worldFolder = Instance.new("Folder")',
    `    worldFolder.Name = "${safeScene}_Zone"`,
    '    worldFolder.Parent = Workspace',
    '',
  ];

  placedAssetNames.forEach((assetName, i) => {
    const offsetX = (i - Math.floor(placedAssetNames.length / 2)) * 18;
    lines.push(
      `    -- Spatial MeshPart Anchor for Asset: ${assetName}`,
      `    local anchor_${i + 1} = Instance.new("MeshPart")`,
      `    anchor_${i + 1}.Name = "${assetName}_SpawnPad"`,
      `    anchor_${i + 1}.Size = Vector3.new(10, 0.6, 10)`,
      `    anchor_${i + 1}.Position = Vector3.new(${offsetX}, 0.3, 0)`,
      `    anchor_${i + 1}.Anchored = true`,
      `    anchor_${i + 1}.Material = Enum.Material.Metal`,
      `    anchor_${i + 1}.Color = Color3.fromRGB(30, 41, 59)`,
      `    anchor_${i + 1}:SetAttribute("SpawnTargetAsset", "${assetName}")`,
      `    anchor_${i + 1}.Parent = worldFolder`,
      ''
    );
  });

  lines.push(
    '    return worldFolder',
    'end',
    '',
    `return ${safeScene}World`
  );
  return lines.join('\n');
}
